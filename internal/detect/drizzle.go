package detect

import (
	"encoding/json"
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/LysCongThanh/migrate-lanes/internal/lane"
)

// drizzleDetector checks drizzle-kit output folders: "<out>/meta/_journal.json"
// lists generated migrations by idx and tag. Two branches that each run
// `drizzle-kit generate` both claim the next idx with different tags and
// snapshots, which breaks the snapshot chain after merge (drizzle-orm#2488).
type drizzleDetector struct{}

// NewDrizzle returns the drizzle-kit journal detector.
func NewDrizzle() Detector { return drizzleDetector{} }

func (drizzleDetector) Tool() string { return "drizzle" }

const drizzleJournal = "meta/_journal.json"

const drizzleAdvice = "drop the lane's generated migration (sql, snapshot, journal entry), rebase on base, then re-run `drizzle-kit generate`"

func (drizzleDetector) Claim(l *lane.Lane) []string {
	var dirs []string
	for _, f := range l.Files {
		if f == drizzleJournal || strings.HasSuffix(f, "/"+drizzleJournal) {
			dirs = append(dirs, path.Dir(path.Dir(f)))
		}
	}
	return dirs
}

type drizzleEntry struct {
	Idx int    `json:"idx"`
	Tag string `json:"tag"`
}

// readJournal returns the journal entries of a lane; ok=false when the lane
// has no journal in dir.
func readJournal(l *lane.Lane, dir string) (entries []drizzleEntry, ok bool, err error) {
	p := path.Join(dir, drizzleJournal)
	if !l.Has(p) {
		return nil, false, nil
	}
	b, err := l.Read(p)
	if err != nil {
		return nil, true, err
	}
	var j struct {
		Entries []drizzleEntry `json:"entries"`
	}
	if err := json.Unmarshal(b, &j); err != nil {
		return nil, true, err
	}
	return j.Entries, true, nil
}

func (drizzleDetector) Analyze(dir string, base *lane.Lane, lanes []*lane.Lane) []Finding {
	var findings []Finding
	journal := path.Join(dir, drizzleJournal)
	baseEntries, _, err := readJournal(base, dir)
	if err != nil {
		findings = append(findings, drizzleParseError(dir, journal, base.Name, err))
	}
	baseByIdx, baseTags := map[int]string{}, map[string]bool{}
	for _, e := range baseEntries {
		baseByIdx[e.Idx], baseTags[e.Tag] = e.Tag, true
	}
	// added: idx -> tag -> lanes, for entries absent from base.
	added := map[int]map[string][]string{}
	for _, l := range lanes {
		entries, ok, err := readJournal(l, dir)
		if !ok {
			continue
		}
		if err != nil {
			findings = append(findings, drizzleParseError(dir, journal, l.Name, err))
			continue
		}
		for _, e := range entries {
			if baseTags[e.Tag] {
				continue
			}
			if added[e.Idx] == nil {
				added[e.Idx] = map[string][]string{}
			}
			added[e.Idx][e.Tag] = append(added[e.Idx][e.Tag], l.Name)
		}
	}
	idxs := make([]int, 0, len(added))
	for idx := range added {
		idxs = append(idxs, idx)
	}
	sort.Ints(idxs)
	for _, idx := range idxs {
		tags := added[idx]
		baseTag, inBase := baseByIdx[idx]
		if !inBase && len(tags) < 2 {
			continue
		}
		f := Finding{Tool: "drizzle", Dir: dir, Kind: KindDuplicate, Version: fmt.Sprint(idx), Advice: drizzleAdvice,
			Message: fmt.Sprintf("journal idx %d is generated by %d lanes with different tags", idx, len(tags))}
		if inBase {
			f.Kind = KindJournal
			f.Message = fmt.Sprintf("journal idx %d already exists on base as %q; lane journal diverged (generated before rebasing)", idx, baseTag)
			f.Entries = append(f.Entries, Entry{Lane: base.Name, File: path.Join(dir, baseTag+".sql")})
		}
		for _, tag := range sortedKeys(tags) {
			for _, ln := range tags[tag] {
				f.Entries = append(f.Entries, Entry{Lane: ln, File: path.Join(dir, tag+".sql")})
			}
		}
		findings = append(findings, f)
	}
	return findings
}

func drizzleParseError(dir, journal, laneName string, err error) Finding {
	return Finding{Tool: "drizzle", Dir: dir, Kind: KindParseError,
		Message: fmt.Sprintf("cannot parse %s: %v (unresolved merge conflict?)", journal, err),
		Entries: []Entry{{Lane: laneName, File: journal}}}
}
